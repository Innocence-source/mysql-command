/*
1. 主键约束 primary key
   特点：值唯一、且不允许为空、一张表 最多只允许设置 1 个主键

2. 唯一约束 unique
   特点： 值唯一 、但允许为空

3. (非)空约束 not null
   特点：限定值是否允许为空、默认采用 null 约束

4. 默认约束 default
   特点：当插入数据的时候，可以给 某字段设置 默认值

5. 检查约束 check
   MySQL 数据库暂不支持，只保留了 关键字

6. 外键约束 foreign key
   作用：维护表与表之间的关系、数据与数据之间的关系
	 
7. 自增约束 auto_increment
		自动生成唯一数值，常用于主键列 
*/
